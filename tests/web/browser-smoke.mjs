import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';

await mkdir('web-smoke-artifacts',{recursive:true});
const browser=await chromium.launch({headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  // Test-only interception: grant XP to exercise UI without waiting for random encounters.
  // The production module does not expose its game state.
  await page.route('**/js/index.js',async route=>{
    const response=await route.fetch();
    const source=await response.text();
    const marker='const game=new Game(config), clock=new FixedClock();';
    assert.ok(source.includes(marker));
    await route.fulfill({response,body:source.replace(marker,marker+'\nwindow.__wizardTestGame=game;')});
  });
  await page.goto('http://127.0.0.1:8000/');
  const start=page.locator('#startButton');
  await start.waitFor({state:'visible'});await page.waitForFunction(()=>!document.getElementById('startButton').disabled);
  await page.screenshot({path:'web-smoke-artifacts/title.png'});
  assert.equal(await page.locator('#starterCards .starter-card').count(),5);
  await page.locator('[data-school="ice"]').click();
  await start.click();
  await page.locator('#overlay').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.getElementById('spellBuild').textContent.includes('Cryomancy 1'));
  const canvas=page.locator('#gameArea');
  const size=await canvas.boundingBox();assert.ok(size.width>1000&&size.height>500);
  await page.keyboard.down('KeyD');await page.keyboard.down('ArrowRight');
  await page.waitForFunction(()=>document.getElementById('timer').textContent!=='00:00');
  await page.keyboard.up('KeyD');await page.keyboard.up('ArrowRight');
  await page.screenshot({path:'web-smoke-artifacts/gameplay.png'});
  // Force a safe showcase through test-only access to simulation state.
  await page.evaluate(()=>{
    const g=window.__wizardTestGame,p=g.player,x=p.x+p.width/2,y=p.y+p.height/2,t=g.tick;
    g.hazards.push({type:'web',x:x+100,y:y+70,radius:46,activeAt:t,until:t+500,damage:0,hit:false});
    g.hazards.push({type:'web',x:x-100,y:y+70,radius:46,activeAt:t+100,until:t+500,damage:0,hit:false});
    g.enemies.push({name:'Goblin',imageSrc:'./images/enemies/goblin.png',x:x+85,y:y-100,width:30,height:30,health:100,maxHealth:100,maxSpeed:0,damage:0,expGiven:0,cd:0,burnUntil:t+500,burnNext:t+500,slowUntil:t+500,slowFactor:.5,freezeUntil:t+500,curseUntil:t+500});
    p.magic.ranks.arcane=2;p.magic.shieldReady=true;
  });
  await page.waitForTimeout(120);
  await page.screenshot({path:'web-smoke-artifacts/elemental-effects.png'});
  await page.locator('#effectsMode').selectOption('off');
  await page.waitForTimeout(120);
  await page.screenshot({path:'web-smoke-artifacts/essential-telegraphs.png'});
  await page.locator('#effectsMode').selectOption('full');
  await page.evaluate(()=>{const g=window.__wizardTestGame;g.enemies=[];g.hazards=[];g.player.magic.ranks.arcane=0;g.player.magic.shieldReady=false;});
  await page.evaluate(()=>{const game=window.__wizardTestGame;game.player.currentExp=game.player.expNeeded;});
  await page.locator('#upgradePanel').waitFor({state:'visible'});
  assert.equal(await page.locator('#upgradeCards .upgrade-card').count(),3);
  assert.ok((await page.locator('#upgradeHint').textContent()).includes('level 10'));
  assert.ok(await page.evaluate(()=>window.__wizardTestGame.offers.filter(o=>o.kind==='school').every(o=>o.id==='ice')));
  await page.screenshot({path:'web-smoke-artifacts/spell-upgrades.png'});
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('KeyQ');
  await page.locator('#overlay').waitFor({state:'hidden'});
  assert.ok((await page.locator('#spellBuild').textContent()).includes('Cryomancy'));
  assert.ok(await page.evaluate(()=>window.__wizardTestGame.player.level>=2));
  await page.evaluate(()=>{const g=window.__wizardTestGame;g.player.level=9;g.player.currentExp=g.player.expNeeded;});
  await page.locator('#upgradePanel').waitFor({state:'visible'});
  assert.ok((await page.locator('#upgradeHint').textContent()).includes('permanent'));
  const secondary=await page.evaluate(()=>window.__wizardTestGame.offers.findIndex(o=>o.kind==='school'&&o.rank===0));
  assert.ok(secondary>=0);
  assert.ok((await page.locator('#upgradeCards .upgrade-card').nth(secondary).locator('.synergy-preview').textContent()).includes('Fusion:'));
  await page.locator('#upgradeCards .upgrade-card').nth(secondary).click();
  await page.waitForFunction(()=>document.getElementById('spellBuild').textContent.includes('Two schools learned'));
  await page.evaluate(()=>{const g=window.__wizardTestGame,p=g.player;g.dropChest(p.x+20,p.y+20,2,'Test treasure');});
  await page.locator('#lootPanel').waitFor({state:'visible'});
  assert.equal(await page.locator('#lootCards .loot-card').count(),3);
  const lootTick=await page.evaluate(()=>window.__wizardTestGame.tick);
  await page.screenshot({path:'web-smoke-artifacts/loot.png'});
  assert.equal(await page.evaluate(()=>window.__wizardTestGame.tick),lootTick);
  await page.locator('#lootCards .loot-card').first().click();
  await page.locator('#overlay').waitFor({state:'hidden'});
  await page.waitForFunction(()=>window.__wizardTestGame.lootHistory.length===1);
  assert.equal(await page.locator('#equipmentBuild .gear-chip').count(),4);
  await page.evaluate(()=>{const g=window.__wizardTestGame,p=g.player;g.dropChest(p.x+20,p.y+20,2,'Test treasure');});
  await page.locator('#lootPanel').waitFor({state:'visible'});
  await page.locator('#skipLoot').click();await page.locator('#overlay').waitFor({state:'hidden'});
  assert.equal(await page.evaluate(()=>window.__wizardTestGame.lootHistory.length),1);
  await page.keyboard.press('Escape');await page.locator('#pausePanel').waitFor({state:'visible'});
  const time=await page.locator('#timer').textContent();await page.waitForTimeout(1200);assert.equal(await page.locator('#timer').textContent(),time);
  await page.screenshot({path:'web-smoke-artifacts/pause.png'});
  await page.locator('#restartButton').click();await page.locator('#confirmPanel').waitFor({state:'visible'});
  await page.locator('#cancelButton').click();await page.locator('#pausePanel').waitFor({state:'visible'});
  await page.locator('#resumeButton').click();await page.locator('#overlay').waitFor({state:'hidden'});
  await page.locator('#effectsMode').selectOption('off');assert.equal(await page.locator('#effectsMode').inputValue(),'off');
  await page.locator('#effectsMode').selectOption('reduced');assert.equal(await page.locator('#effectsMode').inputValue(),'reduced');
  await page.locator('#effectsMode').selectOption('full');
  await page.setViewportSize({width:800,height:700});
  await page.waitForFunction(()=>document.getElementById('gameArea').width===document.getElementById('arena').clientWidth);
  assert.ok((await canvas.boundingBox()).width<800);
  await page.keyboard.press('Escape');await page.locator('#pausePanel').waitFor({state:'visible'});
  await page.locator('#restartButton').click();await page.locator('#confirmButton').click();
  await page.locator('#overlay').waitFor({state:'hidden'});assert.equal(await page.locator('#kills').textContent(),'0');
  await page.keyboard.press('Escape');await page.locator('#pausePanel').waitFor({state:'visible'});
  await page.locator('#quitButton').click();await page.locator('#confirmButton').click();
  await page.locator('#homePanel').waitFor({state:'visible'});
  await page.screenshot({path:'web-smoke-artifacts/compact-title.png'});
  await start.click();await page.locator('#overlay').waitFor({state:'hidden'});
  await page.evaluate(()=>{const g=window.__wizardTestGame;g.tick=25*60*50;g.spawnEnemies();});
  await page.locator('#bossHud').waitFor({state:'visible'});
  assert.ok((await page.locator('#bossName').textContent()).includes('Ancient Dragon'));
  await page.screenshot({path:'web-smoke-artifacts/boss.png'});
  await page.evaluate(()=>{const g=window.__wizardTestGame;g.enemies=g.enemies.filter(e=>!e.miniboss);g.boss.expGiven=0;g.damage(g.boss,g.boss.health);});
  await page.locator('#victoryPanel').waitFor({state:'visible'});
  await page.screenshot({path:'web-smoke-artifacts/victory.png'});
  await page.locator('#endlessButton').click();
  await page.locator('#overlay').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.getElementById('bossName').textContent==='Endless survival');
  assert.deepEqual(errors,[]);
  console.log('Browser smoke passed: assets, start, movement input, pause, confirmation, effects, resizing, restart, return to title.');
}finally{await browser.close();}
